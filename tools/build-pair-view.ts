/* Builds drivers/doorbell/pair/setup.html from tools/pair-view/setup.html with jsQR inlined. */
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(__dirname, '..');
const template = fs.readFileSync(path.join(__dirname, 'pair-view', 'setup.html'), 'utf8');
const jsqr = fs.readFileSync(path.join(root, 'node_modules', 'jsqr', 'dist', 'jsQR.js'), 'utf8');

if (!template.includes('/*__JSQR__*/')) throw new Error('The template has no /*__JSQR__*/ placeholder');

// jsQR's UMD bundle sets window.jsQR when there is no module system; hide any the webview might have.
const wrapped = `(function () { var module, exports, define; ${jsqr}\n}).call(window);`;
const output = template
    .replace(/<!--[\s\S]*?-->\n/, '<!-- Generated by tools/build-pair-view.ts from tools/pair-view/setup.html. Do not edit. -->\n')
    .replace('/*__JSQR__*/', () => wrapped.replace(/<\/script/gi, '<\\/script'));

const target = path.join(root, 'drivers', 'doorbell', 'pair', 'setup.html');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Wrote ${path.relative(root, target)} (${(output.length / 1024).toFixed(0)} KiB)`);
